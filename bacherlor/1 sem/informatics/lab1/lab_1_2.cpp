#include <iostream>
using namespace std;

main(){
    /*  
        1) 	n++-m
        2) 	m-- >n
        3) 	n-- >m
    */
    int m = 5, n = 5;
    cout << n++-m << endl; // n будет использована, а потом изменена на один, а будет 5-5 то есть вывод 0
    cout << (m-- > n) << endl; //n будет использована, а потом изменена на один 5 > 6 - 0
    cout << (n-- > m); // n будет использована, а потом изменена на один 5 > 4 - 1
    return 0;
}